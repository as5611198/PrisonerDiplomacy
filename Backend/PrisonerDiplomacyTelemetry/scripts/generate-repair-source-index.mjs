import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "..", "..", "..");
const sourceRoot = path.join(repositoryRoot, "Source", "PrisonerDiplomacy");
const outputPath = path.join(
  repositoryRoot,
  "Backend",
  "PrisonerDiplomacyTelemetry",
  "src",
  "repair-source-index.generated.ts"
);
const checkOnly = process.argv.includes("--check");

const ignoredCallNames = new Set([
  "catch", "checked", "default", "delegate", "do", "else", "false", "finally",
  "fixed", "for", "foreach", "if", "is", "lock", "nameof", "new", "null",
  "return", "sizeof", "stackalloc", "switch", "throw", "true", "typeof", "unchecked",
  "using", "while"
]);

async function enumerateCSharpFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...await enumerateCSharpFiles(fullPath));
    } else if (entry.isFile() && entry.name.endsWith(".cs")) {
      files.push(fullPath);
    }
  }
  return files;
}

function uniqueSorted(values) {
  return [...new Set(values)].sort((left, right) => left.localeCompare(right));
}

function extractMatches(source, expression, group) {
  const results = [];
  for (const match of source.matchAll(expression)) {
    if (match[group]) {
      results.push(match[group]);
    }
  }
  return results;
}

async function buildIndex() {
  const files = await enumerateCSharpFiles(sourceRoot);
  const entries = [];
  for (const file of files) {
    const source = await readFile(file, "utf8");
    const symbols = uniqueSorted(extractMatches(
      source,
      /\b(?:class|struct|interface|enum)\s+([A-Za-z_][A-Za-z0-9_]*)/g,
      1
    ));
    const calls = extractMatches(source, /\b([A-Za-z_][A-Za-z0-9_]*)\s*\(/g, 1)
      .filter(name => !ignoredCallNames.has(name));
    entries.push({
      path: path.relative(repositoryRoot, file).replaceAll(path.sep, "/"),
      symbols,
      methods: uniqueSorted(calls)
    });
  }
  return entries;
}

function serialize(entries) {
  return [
    "// Generated by scripts/generate-repair-source-index.mjs. Do not edit manually.",
    "export interface RepairSourceIndexEntry {",
    "  path: string;",
    "  symbols: readonly string[];",
    "  methods: readonly string[];",
    "}",
    "",
    `export const REPAIR_SOURCE_INDEX = ${JSON.stringify(entries, null, 2)} as const satisfies readonly RepairSourceIndexEntry[];`,
    ""
  ].join("\n");
}

const entries = await buildIndex();
const expected = serialize(entries);
if (checkOnly) {
  let actual = "";
  try {
    actual = await readFile(outputPath, "utf8");
  } catch {
    // Report the same actionable failure for a missing or stale generated file.
  }
  if (actual !== expected) {
    console.error("repair source index is stale; run npm run generate-source-index");
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, expected, "utf8");
  console.log(`generated repair source index for ${entries.length} C# files`);
}
